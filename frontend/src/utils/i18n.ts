/**
 * Lấy ngôn ngữ hiện tại:
 * 1. Nếu người dùng đã chọn trước đó -> lấy từ localStorage
 * 2. Nếu là khách truy cập lần đầu: Tự động phát hiện qua ngôn ngữ trình duyệt (navigator.languages)
 *    - Nếu trình duyệt là tiếng Việt (vi, vi-VN) -> 'vi'
 *    - Nếu trình duyệt là ngôn ngữ khác (en, fr, de, ja, ko, zh, ...) -> Tự động bật 'en' cho khách nước ngoài!
 */
export const getStoredLanguage = (): Language => {
  if (typeof window === "undefined") return "vi";
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  if (stored === "en" || stored === "vi") {
    return stored;
  }
  try {
    const navLangs = navigator.languages || [navigator.language || (navigator as unknown as { userLanguage?: string }).userLanguage || ""];
    for (const l of navLangs) {
      if (l && l.toLowerCase().startsWith("vi")) {
        return "vi";
      }
    }
    return "en";
  } catch {
    return "en";
  }
};

/**
 * Lưu ngôn ngữ và phát event
 */
export const setLanguage = (lang: Language): void => {
  if (typeof window === "undefined") return;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: { language: lang } }));
};

/**
 * Toggle nhanh giữa Tiếng Việt và Tiếng Anh
 */
export const toggleLanguage = (): Language => {
  const current = getStoredLanguage();
  const next: Language = current === "vi" ? "en" : "vi";
  setLanguage(next);
  return next;
};

/**
 * Hàm dịch văn bản theo key
 */
export const t = (key: string, fallback?: string): string => {
  const lang = getStoredLanguage();
  return TRANSLATIONS[lang]?.[key] || fallback || key;
};

/**
 * React Hook quản lý ngôn ngữ giao diện
 */
export const useTranslation = (): {
  lang: Language;
  setLanguage: (lang: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, fallback?: string) => string;
} => {
  const [lang, setLocalLang] = useState<Language>(getStoredLanguage);

  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === LANG_STORAGE_KEY) {
        setLocalLang((e.newValue as Language) || "vi");
      }
    };

    const handleCustom = (e: Event) => {
      const customEvent = e as CustomEvent<{ language: Language }>;
      if (customEvent.detail?.language) {
        setLocalLang(customEvent.detail.language);
      }
    };

    window.addEventListener("storage", handleStorage);
    window.addEventListener(LANG_EVENT, handleCustom);

    return () => {
      window.removeEventListener("storage", handleStorage);
      window.removeEventListener(LANG_EVENT, handleCustom);
    };
  }, []);

  const translate = useCallback(
    (key: string, fallback?: string) => {
      return TRANSLATIONS[lang]?.[key] || fallback || key;
    },
    [lang]
  );

  return {
    lang,
    setLanguage: (l: Language) => setLanguage(l),
    toggleLanguage: () => toggleLanguage(),
    t: translate,
  };
};
